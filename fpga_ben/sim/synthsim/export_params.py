"""RTL parameter & memory export (CONTRACT.md s5).

Re-emits the frozen Python ``SynthParams`` as a Verilog header
(``synth_params.vh``) and dumps the wavetable mipmaps as ``.mem`` files so the
RTL consumes exactly what the golden model simulated.
"""
from __future__ import annotations

import math
import os
from typing import List

try:
    from . import params as _params_mod
except Exception:  # pragma: no cover - absolute fallback
    import synthsim.params as _params_mod  # type: ignore


def _fmt_verilog(value):
    """Plain Verilog literal for a Python value (no Python types leak)."""
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, float):
        s = "%.6f" % value
        s = s.rstrip("0").rstrip(".")
        if "." not in s:
            s += ".0"
        return s
    return str(value)


def _mac(name, value):
    return "`define %-20s %s" % (name, _fmt_verilog(value))


def _clog2(n):
    n = int(n)
    return max(0, (n - 1).bit_length())


def _out_dir():
    return os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                        "..", "out"))


def export_verilog_header(params, path):
    """Write ``synth_params.vh``: one ``define`` per frozen SynthParams field,
    RTL sizing macros, DEVICE figures and the frequency-word formula."""
    p = params
    dev = _params_mod.DEVICE
    lines = []
    lines.append("// -----------------------------------------------------------------------------")
    lines.append("// synth_params.vh - AUTO-GENERATED by synthsim golden model. Do not edit.")
    lines.append("// Target device: %s" % dev["name"])
    lines.append("// -----------------------------------------------------------------------------")
    lines.append("`ifndef SYNTH_PARAMS_VH")
    lines.append("`define SYNTH_PARAMS_VH")
    lines.append("")
    lines.append("// ---- clock / audio interface ----")
    lines.append(_mac("SR", p.sr))
    lines.append(_mac("MASTER_CLK_HZ", p.master_clk_hz))
    lines.append(_mac("NYQUIST_HZ", int(p.nyquist)))
    lines.append("")
    lines.append("// ---- oscillator ----")
    lines.append(_mac("PHASE_BITS", p.phase_bits))
    lines.append(_mac("TABLE_SIZE", p.table_size))
    lines.append(_mac("TABLE_BITS", p.table_bits))
    lines.append(_mac("TABLE_ADDR_BITS", int(round(math.log2(p.table_size)))))
    lines.append(_mac("INTERP_LINEAR", p.interp == "linear"))
    lines.append(_mac("INTERP_NONE", p.interp == "none"))
    lines.append("")
    lines.append("// ---- envelope (ADSR) ----")
    lines.append(_mac("ENV_BITS", p.env_bits))
    lines.append(_mac("ADSR_ATTACK_MS", p.adsr_attack_ms))
    lines.append(_mac("ADSR_DECAY_MS", p.adsr_decay_ms))
    lines.append(_mac("ADSR_SUSTAIN", p.adsr_sustain))
    lines.append(_mac("ADSR_RELEASE_MS", p.adsr_release_ms))
    lines.append(_mac("ADSR_ATTACK_SAMPLES",
                      int(round(p.adsr_attack_ms * p.sr / 1000.0))))
    lines.append(_mac("ADSR_DECAY_SAMPLES",
                      int(round(p.adsr_decay_ms * p.sr / 1000.0))))
    lines.append(_mac("ADSR_RELEASE_SAMPLES",
                      int(round(p.adsr_release_ms * p.sr / 1000.0))))
    lines.append(_mac("ADSR_SUSTAIN_Q%d" % p.env_bits,
                      int(round(p.adsr_sustain * ((1 << p.env_bits) - 1)))))
    lines.append(_mac("ADSR_CURVE_EXP", p.adsr_curve == "exp"))
    lines.append(_mac("ADSR_CURVE_LIN", p.adsr_curve == "lin"))
    lines.append("")
    lines.append("// ---- polyphony / mixing ----")
    lines.append(_mac("MAX_VOICES", p.max_voices))
    lines.append(_mac("VOICE_ADDR_BITS", _clog2(p.max_voices)))
    lines.append(_mac("VOICE_GAIN_SHIFT", p.voice_gain_shift))
    lines.append(_mac("SATURATE", p.saturate))
    lines.append("")
    lines.append("// ---- wavetable anti-aliasing (mipmap) ----")
    lines.append(_mac("MIP_OCTAVES", p.mip_octaves))
    lines.append(_mac("MIP_ADDR_BITS", _clog2(p.mip_octaves)))
    lines.append(_mac("BASE_MAX_HARMONICS", p.base_max_harmonics))
    lines.append("")
    lines.append("// ---- latency budget ----")
    lines.append(_mac("I2S_FIFO_DEPTH", p.i2s_fifo_depth))
    lines.append(_mac("SCAN_BLOCK", p.scan_block))
    lines.append("")
    lines.append("// ---- test mode (rule 3: N independent spectral peaks) ----")
    lines.append(_mac("TEST_TONES", p.test_tones))
    lines.append(_mac("TEST_F0_HZ", p.test_f0_hz))
    lines.append(_mac("TEST_SPACING_HZ", p.test_spacing_hz))
    lines.append(_mac("TEST_SECONDS", p.test_seconds))
    lines.append("")
    lines.append("// ---- target device ----")
    lines.append("`define %-20s %s" % ("DEVICE_NAME", '"%s"' % dev["name"]))
    lines.append(_mac("DEVICE_LUT", dev["lut"]))
    lines.append(_mac("DEVICE_FF", dev["ff"]))
    lines.append(_mac("DEVICE_DSP", dev["dsp"]))
    lines.append(_mac("DEVICE_BSRAM_KB", dev["bsram_kb"]))
    lines.append(_mac("DEVICE_PLL", dev["pll"]))
    lines.append("")
    lines.append("// ---- frequency word (phase increment) ----")
    lines.append("// FWORD = round( freq_hz * 2**PHASE_BITS / SR )")
    fw_a4 = p.freq_word(440.0)
    fw_f0 = p.freq_word(p.test_f0_hz)
    lines.append("//   Example: A4 = 440 Hz @ SR = %d -> FWORD = %d (0x%08X)"
                 % (p.sr, fw_a4, fw_a4))
    lines.append("//   Example: test f0 = %.1f Hz   -> FWORD = %d (0x%08X)"
                 % (p.test_f0_hz, fw_f0, fw_f0))
    lines.append("")
    lines.append("`endif // SYNTH_PARAMS_VH")
    d = os.path.dirname(os.path.abspath(path))
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def export_wavetables(params, out_dir):
    """Emit wavetable ``.mem`` files via synthsim.wavetable; degrade gracefully
    (return []) if that module is not built yet."""
    try:
        from . import wavetable as _wt
        os.makedirs(out_dir, exist_ok=True)
        paths = []
        sine_tables = [_wt.generate_sine(int(params.table_size),
                                         int(params.table_bits))]
        p = os.path.join(out_dir, "wavetable_sine.mem")
        _wt.write_mem(sine_tables, p, int(params.table_bits),
                      int(params.table_size), "sine")
        paths.append(p)
        for kind in ("saw", "square", "triangle"):
            tables = _wt.build_mipmap(kind, int(params.table_size),
                                      int(params.table_bits),
                                      int(params.mip_octaves),
                                      int(params.base_max_harmonics))
            p = os.path.join(out_dir, "wavetable_%s.mem" % kind)
            _wt.write_mem(tables, p, int(params.table_bits),
                          int(params.table_size), kind)
            paths.append(p)
        return paths
    except Exception as exc:  # sibling module missing or mid-build
        print("export_wavetables: synthsim.wavetable unavailable (%s); no .mem"
              " files written" % exc)
        return []


def _self_test():
    p = _params_mod.PARAMS_48K
    header = os.path.join(_out_dir(), "synth_params.vh")
    export_verilog_header(p, header)
    print("export_verilog_header: wrote %s" % header)
    with open(header, "r") as fh:
        first = fh.read().splitlines()[:20]
    print("---- first 20 lines of synth_params.vh ----")
    for line in first:
        print(line)
    print("-------------------------------------------")
    paths = export_wavetables(p, os.path.join(_out_dir(), "wavetables"))
    if paths:
        for path in paths:
            print("export_wavetables: %s" % path)
    else:
        print("export_wavetables: skipped (synthsim.wavetable not ready yet)")
    print("EXPORT_PARAMS SELF-TEST OK")


if __name__ == "__main__":
    _self_test()
