"""Generate Q15 FFT ROMs and compile-time frequency band maps."""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rtl" / "visualizer"
N = 4096


def q15(value):
    return max(-32768, min(32767, round(value * 32768))) & 0xFFFF


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    twiddle = [f"{q15(math.cos(2*math.pi*k/N)):04x}{q15(-math.sin(2*math.pi*k/N)):04x}"
               for k in range(N // 2)]
    hann = [f"{q15(0.5 - 0.5*math.cos(2*math.pi*k/N)):04x}" for k in range(N)]
    (OUT / "fft_twiddle.hex").write_text("\n".join(twiddle) + "\n", encoding="ascii")
    (OUT / "fft_hann.hex").write_text("\n".join(hann) + "\n", encoding="ascii")

    def threshold(hz):
        numerator = math.ceil(hz * 512 * N)
        return f"((64'd{numerator} * AUDIO_BCK_DIV + 64'd49999999) / 64'd50000000)"

    lines = ["// Generated by tools/gen_visualizer_tables.py; all divisions are constant.",
             "function [5:0] spectrum_band;", "    input [11:0] bin_number;", "    begin",
             f"        if (bin_number < {threshold(64)}) spectrum_band = 6'd63;"]
    for band in range(32):
        lines.append(f"        else if (bin_number < {threshold(64 * 2**((band+1)/4))}) spectrum_band = 6'd{band};")
    lines += ["        else spectrum_band = 6'd63;", "    end", "endfunction", "",
              "function [5:0] benchmark_band;", "    input [11:0] bin_number;", "    begin"]
    for band in range(32):
        hz = (band + 1) * 200
        prefix = "if" if band == 0 else "else if"
        lines.append(f"        {prefix} (bin_number >= {threshold(hz-75)} && bin_number < {threshold(hz+75)}) benchmark_band = 6'd{band};")
    lines += ["        else benchmark_band = 6'd63;", "    end", "endfunction", ""]
    (OUT / "fft_bands.vh").write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    main()
